#!/usr/bin/env python3
"""
select_approved_items: an item is built only when the cloud record and the
latest Agent Brief both approve it; every other item is reported, not built.

Run: python -m pytest -q scripts/tests/test_select_approved_items.py

The suggestions below are invented for this test.
"""

import importlib.util
import io
import json
import os
import tempfile
import unittest
from contextlib import redirect_stderr, redirect_stdout
from pathlib import Path

SCRIPTS = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_spec = importlib.util.spec_from_file_location("select_approved_items", os.path.join(SCRIPTS, "select_approved_items.py"))
sel = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(sel)

SID = "3b6f1c2a-9d4e-4f7a-8b1c-2d3e4f5a6b7c"
OTHER = "7c6b5a4f-3e2d-4c1b-8a9f-0e1d2c3b4a59"


def record(sid=SID, statuses=("approved", "declined")):
    return {
        "suggestion_id": sid,
        "status": "under review",
        "body": "An invented pain point for this test, about a report that is hard to read.",
        "item_list": [{"item": n, "text": f"Invented item {n} text for the selection test", "status": st,
                       "reason": None if st == "undecided" else "A reason", "category": None,
                       "implemented_in": "lawyer 0.3.1" if st == "implemented" else None}
                      for n, st in enumerate(statuses, 1)],
    }


TRIAGE_BRIEF = f"""> *This was generated by AI during triage.*

## Agent Brief

Suggestion {SID}

### Item 1
**Item:** lines per matter.

### Item 2
**Item:** bold the total.

### Open decisions
Item 1: approve or decline? Recommended: approve.
"""

DECIDED_BRIEF = f"""> *Decisions recorded by /suggestion-hitl-triage.*

## Agent Brief

Suggestion {SID}

**Verification:** held.

### Item 1
**Item:** one line per matter.
**Check:** `tests/test_one.py`.
**Plan:** 1. Split the lines.

### Scope
`report.py` only.

### Done when
Item 1: `python -m pytest tests/test_one.py`.

### Decisions
- Item 1: approved. Easier to scan.
- Item 2: declined (cost outweighs benefit). Not worth the change.
"""


def issue(*comments, body=f"Paraphrase of the suggestion.\n\nSuggestion {SID}\n"):
    return {"body": body, "comments": [{"body": c} for c in comments]}


class SelectTest(unittest.TestCase):
    def select(self, the_issue, *records, pages=()):
        return sel.select(the_issue, list(pages), {r["suggestion_id"]: r for r in records})

    def test_builds_only_the_item_both_approve(self):
        got = self.select(issue(TRIAGE_BRIEF, DECIDED_BRIEF), record())
        self.assertEqual(got["suggestion_id"], SID)
        self.assertEqual(got["brief"], "comment")
        self.assertEqual(got["build"], [{"suggestion_id": SID, "item": 1, "also": [],
                                         "refs": [f"Suggestion {SID} item 1"]}])
        self.assertEqual([(n["item"], n["why"]) for n in got["not_built"]],
                         [(2, "declined in the cloud record and declined in the brief")])

    def test_approved_in_the_record_only_is_not_built(self):
        got = self.select(issue(DECIDED_BRIEF), record(statuses=("approved", "approved")))
        self.assertEqual([u["item"] for u in got["build"]], [1])
        self.assertIn("approved in the cloud record, but the latest Agent Brief says declined",
                      got["not_built"][0]["why"])

    def test_approved_in_the_brief_only_is_not_built(self):
        got = self.select(issue(DECIDED_BRIEF), record(statuses=("undecided", "declined")))
        self.assertEqual(got["build"], [])
        self.assertIn("approved in the latest Agent Brief, but the cloud record says undecided",
                      got["not_built"][0]["why"])

    def test_already_implemented_is_not_built(self):
        got = self.select(issue(DECIDED_BRIEF), record(statuses=("implemented", "declined")))
        self.assertEqual(got["build"], [])
        self.assertEqual(got["not_built"][0]["why"], "already implemented in lawyer 0.3.1")

    def test_an_approved_item_without_its_section_is_not_built(self):
        brief = DECIDED_BRIEF.replace("### Item 1\n", "### Notes\n")
        got = self.select(issue(brief), record())
        self.assertEqual(got["build"], [])
        self.assertIn("no ### Item 1 section", got["not_built"][0]["why"])

    def test_the_latest_brief_governs(self):
        later = DECIDED_BRIEF.replace("- Item 1: approved. Easier to scan.", "- Item 1: declined (cost outweighs benefit). Changed mind.")
        got = self.select(issue(DECIDED_BRIEF, later), record())
        self.assertEqual(got["build"], [])

    def test_the_triage_brief_alone_approves_nothing(self):
        with self.assertRaisesRegex(sel.Unsettled, "no ### Decisions list"):
            self.select(issue(TRIAGE_BRIEF), record())

    def test_an_item_given_two_decisions_is_unsettled(self):
        brief = DECIDED_BRIEF + "- Item 1: declined (cost outweighs benefit). Contradiction.\n"
        with self.assertRaisesRegex(sel.Unsettled, "two different decisions"):
            self.select(issue(brief), record())

    def test_brief_and_body_naming_different_suggestions_is_unsettled(self):
        with self.assertRaisesRegex(sel.Unsettled, "different suggestions"):
            self.select(issue(DECIDED_BRIEF, body=f"Suggestion {OTHER}\n"), record())

    def test_a_missing_record_is_unsettled(self):
        with self.assertRaisesRegex(sel.Unsettled, "no cloud record"):
            self.select(issue(DECIDED_BRIEF), record(sid=OTHER))

    def test_a_withdrawn_suggestion_builds_nothing(self):
        r = record()
        r["status"] = "withdrawn"
        got = self.select(issue(DECIDED_BRIEF), r)
        self.assertEqual(got["build"], [])
        self.assertTrue(all(n["why"] == "the suggestion was withdrawn" for n in got["not_built"]))

    def test_a_brief_in_the_body_is_read_when_no_comment_holds_one(self):
        body = DECIDED_BRIEF.replace("## Agent Brief\n", "")
        got = self.select(issue(body=body), record())
        self.assertEqual(got["brief"], "body")
        self.assertEqual([u["item"] for u in got["build"]], [1])

    def test_comment_pages_are_read_in_order(self):
        the_issue = {"body": f"Suggestion {SID}\n"}
        got = self.select(the_issue, record(), pages=[[{"body": TRIAGE_BRIEF}], [{"body": DECIDED_BRIEF}]])
        self.assertEqual([u["item"] for u in got["build"]], [1])

    def test_a_merged_suggestion_travels_with_its_matching_item_only_when_approved(self):
        covers = (f"### Also covers\nSuggestion {OTHER}, issue #41\n"
                  f"item 1 = item 1 of Suggestion {SID}\nitem 2 = item 2 of Suggestion {SID}\n")
        other = record(sid=OTHER, statuses=("approved", "approved"))
        got = self.select(issue(covers, DECIDED_BRIEF), record(), other)
        self.assertEqual(got["build"][0]["also"], [{"suggestion_id": OTHER, "item": 1}])
        self.assertEqual(got["build"][0]["refs"], [f"Suggestion {SID} item 1", f"Suggestion {OTHER} item 1"])
        self.assertIn((OTHER, 2, "item 2, which it is merged with, is not built"),
                      [(n["suggestion_id"], n["item"], n["why"]) for n in got["not_built"]])

        declined_other = record(sid=OTHER, statuses=("declined", "approved"))
        got = self.select(issue(covers, DECIDED_BRIEF), record(), declined_other)
        self.assertEqual(got["build"][0]["also"], [])


class MainTest(unittest.TestCase):
    def run_main(self, files):
        with tempfile.TemporaryDirectory() as d:
            args = []
            for flag, data in files:
                path = Path(d) / f"{len(args)}.json"
                path.write_text(json.dumps(data), encoding="utf-8")
                args += [flag, str(path)]
            out, err = io.StringIO(), io.StringIO()
            with redirect_stdout(out), redirect_stderr(err):
                code = sel.main(args)
            return code, out.getvalue(), err.getvalue()

    def test_prints_the_selection(self):
        code, out, _ = self.run_main([("--issue", issue(DECIDED_BRIEF)), ("--record", {"suggestions": [record()]})])
        self.assertEqual(code, 0)
        self.assertEqual([u["item"] for u in json.loads(out)["build"]], [1])

    def test_unsettled_exits_2_and_builds_nothing(self):
        code, out, err = self.run_main([("--issue", issue(TRIAGE_BRIEF)), ("--record", record())])
        self.assertEqual(code, 2)
        self.assertEqual(out, "")
        self.assertIn("nothing is built", err)

    def test_a_record_is_required(self):
        code, _, _ = self.run_main([("--issue", issue(DECIDED_BRIEF))])
        self.assertEqual(code, 2)


if __name__ == "__main__":
    unittest.main()
