#!/usr/bin/env python3
"""
check_brief: a brief holds only checks its run can perform, and sends an issue to
a person only for a reason on the closed list.

Run: python -m pytest -q scripts/tests/test_check_brief.py
"""

import importlib.util
import io
import os
import sys
import tempfile
import unittest
from contextlib import redirect_stderr, redirect_stdout

SCRIPTS = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, SCRIPTS)
_spec = importlib.util.spec_from_file_location("check_brief", os.path.join(SCRIPTS, "check_brief.py"))
cb = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(cb)


def brief(done="- `python -m pytest -q scripts/tests/test_a.py` passes.", plan="1. Edit `scripts/tests/test_a.py`.",
          scope="May change: the one test.", extra=""):
    return (f"> *This was generated by AI during triage.*\n\n## Agent Brief\n\n**State:** ready-for-agent\n\n"
            f"### Plan\n{plan}\n\n### Scope\n{scope}\n\n### Done when\n{done}\n{extra}")


class DoneWhen(unittest.TestCase):
    def test_a_narrow_brief_passes(self):
        self.assertEqual(cb.problems(brief()), [])

    def test_whole_suite_lines_fail(self):
        for line in ("- Run the full `source/lawyer/mcp/test` suite on `main` before and after.",
                     "- `node scripts/test.mjs e2e` passes on Windows.",
                     "- `npm test` passes.",
                     "- `python -m pytest -q scripts/tests` passes.",
                     "- `python -m pytest -q scripts/tests/<file>` passes.",
                     "- `node --test test/` passes."):
            self.assertEqual(len(cb.problems(brief(done=line))), 1, line)

    def test_scheduled_run_lines_fail(self):
        for line in ("- The next scheduled `data-mcp-tests` run no longer lists the file.",
                     "- The nightly `data-mcp-tests` run passes.",
                     "- The next daily run is green."):
            self.assertEqual(len(cb.problems(brief(done=line))), 1, line)

    def test_a_test_file_outside_plan_and_scope_fails(self):
        out = cb.problems(brief(done="- `python -m pytest -q scripts/tests/test_b.py` passes."))
        self.assertEqual(len(out), 1)
        self.assertIn("test_b.py", out[0])

    def test_a_longer_name_does_not_count_for_a_shorter_one(self):
        out = cb.problems(brief(done="- `node --test test/a.test.mjs` passes.", plan="1. Edit `test/aa.test.mjs`."))
        self.assertEqual(len(out), 1)

    def test_a_test_file_named_by_scope_passes(self):
        text = brief(done="- `node --test test/b.unit.test.mjs` passes.", scope="May change: `test/b.unit.test.mjs`.")
        self.assertEqual(cb.problems(text), [])

    def test_a_test_file_named_by_an_item_passes(self):
        text = brief(done="- Item 1: `python x/test_b.py` passes.",
                     extra="\n### Item 1\n**Check:** `x/test_b.py`.\n")
        self.assertEqual(cb.problems(text), [])

    def test_after_landing_may_hold_what_done_when_may_not(self):
        extra = "\n### After landing\n- The next nightly `data-mcp-tests` run no longer lists `test_z.py`.\n"
        self.assertEqual(cb.problems(brief(extra=extra)), [])

    def test_a_heading_inside_a_code_fence_starts_no_section(self):
        extra = "\n### Red tests\n```\n### Done when\n- `npm test`\n```\n"
        self.assertEqual(cb.problems(brief(extra=extra)), [])


class NeedsAPerson(unittest.TestCase):
    def test_an_open_decision_with_a_listed_reason_passes(self):
        extra = "\n### Open decisions\n1. Which version?\nNeeds a person: authorization\n"
        self.assertEqual(cb.problems(brief(extra=extra)), [])

    def test_an_open_decision_with_no_line_fails(self):
        out = cb.problems(brief(extra="\n### Open decisions\n1. Which version?\n"))
        self.assertEqual(len(out), 1)

    def test_a_reason_off_the_list_fails(self):
        extra = "\n### Open decisions\n1. Which name?\nNeeds a person: judgement call\n"
        self.assertEqual(len(cb.problems(brief(extra=extra))), 1)

    def test_each_decision_needs_its_own_line(self):
        extra = "\n### Open decisions\n1. One?\nNeeds a person: suggestion\n2. Two?\n"
        self.assertEqual(len(cb.problems(brief(extra=extra))), 1)

    def test_suggestion_items_count_as_decisions(self):
        extra = ("\n### Open decisions\nItem 1: approve or decline? Recommended: approve.\n"
                 "Needs a person: suggestion\nItem 2: approve or decline? Recommended: approve.\n")
        self.assertEqual(len(cb.problems(brief(extra=extra))), 1)

    def test_a_ready_for_human_brief_with_no_decision_needs_a_reason_too(self):
        text = brief().replace("**State:** ready-for-agent", "**State:** ready-for-human, for a live check.")
        self.assertEqual(len(cb.problems(text)), 1)
        self.assertEqual(cb.problems(text + "\nNeeds a person: person-only-check\n"), [])


class Cli(unittest.TestCase):
    def run_main(self, *argv):
        out, err = io.StringIO(), io.StringIO()
        with redirect_stdout(out), redirect_stderr(err):
            code = cb.main(list(argv))
        return code, out.getvalue()

    def write(self, folder, text):
        path = os.path.join(folder, "brief.md")
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        return path

    def test_exit_codes(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = self.write(tmp, brief())
            self.assertEqual(self.run_main(path)[0], 0)
            path = self.write(tmp, brief(done="- `npm test` passes."))
            code, out = self.run_main(path)
            self.assertEqual(code, 1)
            self.assertIn(path, out)
            path = self.write(tmp, "No brief here.")
            self.assertEqual(self.run_main(path)[0], 2)
        self.assertEqual(self.run_main()[0], 2)


if __name__ == "__main__":
    unittest.main()
