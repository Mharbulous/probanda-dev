#!/usr/bin/env python3
"""Regenerate ../schema.sql from a freshly migrated drafting database.

Migrates a new database in a temporary folder through migrate_engine.py,
then writes the file's six-line header and every sqlite_master.sql entry in
creation order, each ending in ";" and separated by a blank line, with LF
line endings. Stdlib only. schema.sql is never hand-edited: run this after
any change to migrations.sql.

Usage: python regen_schema.py [out_path]   (default: ../schema.sql)
"""

import sqlite3
import sys
import tempfile
from pathlib import Path

import migrate_engine

_SCHEMA_SQL_PATH = Path(__file__).resolve().parent.parent / "schema.sql"

_HEADER = (
    "-- Submission drafting -- canonical schema reference\n"
    "-- Generated by dumping sqlite_master.sql from a database freshly migrated\n"
    "-- via references/scripts/migrate_engine.py. Do not hand-edit: regenerate\n"
    "-- after any change to migrations.sql so this file matches the live schema\n"
    "-- byte-for-byte (this is the acceptance test for issue 295).\n"
    "-- Current version: db_meta.schema_version = {version}\n"
)


def render():
    """The schema.sql text for a database freshly migrated to TARGET_SCHEMA_VERSION."""
    with tempfile.TemporaryDirectory() as tmp:
        db_path = Path(tmp) / "fresh.sqlite"
        migrate_engine.migrate(str(db_path))
        con = sqlite3.connect(str(db_path))
        try:
            version = con.execute("SELECT value FROM db_meta WHERE key = 'schema_version'").fetchone()[0]
            entries = [row[0] for row in con.execute("SELECT sql FROM sqlite_master WHERE sql IS NOT NULL ORDER BY rowid")]
        finally:
            con.close()
    body = "\n".join(sql.replace("\r\n", "\n") + ";\n" for sql in entries)
    return _HEADER.format(version=version) + "\n\n" + body


if __name__ == "__main__":
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else _SCHEMA_SQL_PATH
    out.write_bytes(render().encode("utf-8"))
