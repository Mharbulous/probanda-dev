const PRACTICE_BY_TABLE = new Map(PRACTICE_ENTITIES.map((entity) => [entity.table, entity]));

export function practiceEntityFor(table: string): EntityDefinition {
  const entity = PRACTICE_BY_TABLE.get(table);
  if (!entity) throw new ValidationError(`Unknown practice table "${table}"`);
  return entity;
}
