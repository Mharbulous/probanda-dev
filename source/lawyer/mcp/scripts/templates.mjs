// Board template codegen (map #125; decisions #126, #128, #130).
//
//   node scripts/templates.mjs
//
// Turns each template file (.html, .css, .js) under a template root into a generated module
// beside it, `<file>.ts`, whose default export is the file's text. tsc and esbuild then carry the
// text with no runtime file read. The generated modules are gitignored, so a build that skipped
// this step fails on a missing module. Composing (includes, the data marker) is not done here:
// that is src/compose-template.ts, shared by the boards and the preview tools.
//
// One trailing LF in a template file is not part of its content, so an editor that adds a final
// newline changes nothing. The guards refuse a CR anywhere, `</script` in a .js template and
// `</style` in a .css template, any of which would break a page or its byte-identity.

import { existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { extname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(fileURLToPath(import.meta.url), "..", "..");
export const TEMPLATE_ROOTS = ["src/templates", "src/housekeeping/templates"].map((r) => join(ROOT, r));

const GUARDS = {
  ".html": [],
  ".css": [[/<\/style/i, "</style"]],
  ".js": [[/<\/script/i, "</script"]],
};

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)]
  );
}

/** The text a template file contributes: its content less one trailing LF, after the guards. */
export function templateText(file, raw) {
  const ext = extname(file);
  if (!(ext in GUARDS)) throw new Error(`${file}: not a template (.html, .css or .js)`);
  if (raw.includes("\r")) throw new Error(`${file}: holds a CR; template files are LF only`);
  for (const [pattern, name] of GUARDS[ext]) {
    if (pattern.test(raw)) throw new Error(`${file}: holds ${name}, which would end the page's ${ext === ".js" ? "script" : "style"} block`);
  }
  return raw.endsWith("\n") ? raw.slice(0, -1) : raw;
}

/** Writes `<file>.ts` beside every template under `roots` and deletes generated files left by a removed template. */
export function generate(roots = TEMPLATE_ROOTS) {
  const written = [];
  for (const root of roots.filter((r) => existsSync(r))) {
    const files = walk(root);
    const sources = new Set(files.filter((f) => !f.endsWith(".ts")));
    for (const f of files.filter((f) => f.endsWith(".ts"))) {
      const source = f.slice(0, -3);
      if (!(extname(source) in GUARDS)) throw new Error(`${f}: a .ts file in a template folder that is not a generated template module`);
      if (!sources.has(source)) rmSync(f);
    }
    for (const f of sources) {
      const text = templateText(f, readFileSync(f, "utf-8"));
      const name = relative(root, f).replaceAll("\\", "/");
      const body = `// Generated by scripts/templates.mjs from ${name}. Do not edit.\nexport default ${JSON.stringify(text)};\n`;
      const out = `${f}.ts`;
      if (!existsSync(out) || readFileSync(out, "utf-8") !== body) writeFileSync(out, body);
      written.push(out);
    }
  }
  return written;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  generate();
}
