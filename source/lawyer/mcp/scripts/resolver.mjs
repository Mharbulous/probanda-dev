// Case-data resolver codegen (issue #177).
//
//   node scripts/resolver.mjs
//
// Turns the matter-data skill's case_data_resolver.py into src/case/case-data-resolver.py.ts, whose
// default export is the file's text. Two modules put that text at the head of their embedded
// Python: case/locate.ts, ahead of its pointer read (the driver the files server runs), and
// case/backend.ts, ahead of its helper. So the resolver has one source and the server still reads
// no skill file at run time. The generated module is gitignored, so a build that skipped this step
// fails on a missing module.
//
// The guards refuse a CR, a migrate_only parameter, a resolve_pointer definition and an import of
// resolve_paths: neither locate.ts nor the backend may carry the schema-guard bypass (matter-data
// design-decisions.md #27).

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(fileURLToPath(import.meta.url), "..", "..");
export const RESOLVER_SOURCE = resolve(
  ROOT, "..", "..", "..", "source", "skills", "matter-data", "references", "scripts", "case_data_resolver.py"
);
export const RESOLVER_MODULE = resolve(ROOT, "src", "case", "case-data-resolver.py.ts");

const BYPASS_GUARDS = [
  [/\bmigrate_only\s*=/, "a migrate_only parameter"],
  [/^\s*def\s+resolve_pointer\b/m, "a resolve_pointer definition"],
  [/^\s*(?:import|from)\s+resolve_paths\b/m, "an import of resolve_paths"],
];

/** The resolver's text, after the guards. */
export function resolverText(raw) {
  if (raw.includes("\r")) throw new Error(`${RESOLVER_SOURCE}: holds a CR; it must be LF only`);
  for (const [pattern, name] of BYPASS_GUARDS) {
    if (pattern.test(raw)) {
      throw new Error(`${RESOLVER_SOURCE}: holds ${name}; the backend embeds this file and must not carry the guard bypass`);
    }
  }
  return raw;
}

/** Writes src/case/case-data-resolver.py.ts when its content changed. */
export function generateResolver() {
  const text = resolverText(readFileSync(RESOLVER_SOURCE, "utf-8"));
  const body = `// Generated by scripts/resolver.mjs from the matter-data skill's case_data_resolver.py. Do not edit.\nexport default ${JSON.stringify(text)};\n`;
  if (!existsSync(RESOLVER_MODULE) || readFileSync(RESOLVER_MODULE, "utf-8") !== body) writeFileSync(RESOLVER_MODULE, body);
  return RESOLVER_MODULE;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  generateResolver();
}
