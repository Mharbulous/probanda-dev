// Board template pipeline (map #125): the codegen script, its guards, composeTemplate and the
// sha256-pin helper. Uses synthetic templates only; no generated page is read.

import assert from "node:assert/strict";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";

import { generate, templateText } from "../scripts/templates.mjs";
import { assertSha256Pin, sha256 } from "./helpers/sha256-pin.mjs";

const { composeTemplate } = await import("../build/compose-template.js");

function scratch(t) {
  const dir = mkdtempSync(join(tmpdir(), "templates-"));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  return dir;
}

test("codegen writes <file>.ts exporting the text less one trailing LF", (t) => {
  const root = scratch(t);
  mkdirSync(join(root, "demo"));
  writeFileSync(join(root, "demo", "demo.html"), "<p>a</p>\n\n");
  writeFileSync(join(root, "demo", "board.css"), "p{}");
  const written = generate([root, join(root, "absent")]);
  assert.equal(written.length, 2);
  const body = readFileSync(join(root, "demo", "demo.html.ts"), "utf-8");
  assert.match(body, /^\/\/ Generated by scripts\/templates\.mjs from demo\/demo\.html\. Do not edit\.\n/);
  assert.ok(body.endsWith(`export default ${JSON.stringify("<p>a</p>\n")};\n`));
});

test("codegen deletes a generated module whose template is gone", (t) => {
  const root = scratch(t);
  writeFileSync(join(root, "gone.css.ts"), "export default \"\";\n");
  generate([root]);
  assert.equal(existsSync(join(root, "gone.css.ts")), false);
});

test("codegen refuses a non-template file and a hand-written .ts in a template folder", (t) => {
  const root = scratch(t);
  writeFileSync(join(root, "notes.md"), "x");
  assert.throws(() => generate([root]), /not a template/);
  rmSync(join(root, "notes.md"));
  writeFileSync(join(root, "helper.ts"), "export {};");
  assert.throws(() => generate([root]), /not a generated template module/);
});

test("guards refuse a CR, </script in .js and </style in .css", () => {
  assert.throws(() => templateText("a.html", "<p>\r\n"), /holds a CR/);
  assert.throws(() => templateText("a.js", "x = '</SCRIPT>'"), /holds <\/script/);
  assert.throws(() => templateText("a.css", "/* </style> */"), /holds <\/style/);
  assert.equal(templateText("a.html", "<script></script>\n"), "<script></script>");
  assert.equal(templateText("a.js", "s = '</style>'"), "s = '</style>'");
});

test("composeTemplate resolves nested includes and splits at the data marker", () => {
  const files = {
    "demo.html": "<style>@@include(board.css)@@</style><script>@@data@@\n@@include(page.js)@@</script>",
    "board.css": "p{}@@include(extra.css)@@",
    "extra.css": "b{}",
    "page.js": "run();",
  };
  const { head, tail } = composeTemplate("demo.html", files);
  assert.equal(head, "<style>p{}b{}</style><script>");
  assert.equal(tail, "\nrun();</script>");
});

test("composeTemplate fails on a missing include, a cycle, a bad marker count or a leftover @@", () => {
  assert.throws(() => composeTemplate("a.html", { "a.html": "@@include(b.css)@@@@data@@" }), /"b\.css" is missing \(included by "a\.html"\)/);
  assert.throws(() => composeTemplate("a.html", { "a.html": "@@include(a.html)@@" }), /include cycle/);
  assert.throws(() => composeTemplate("a.html", { "a.html": "x" }), /has 0 @@data@@ markers/);
  assert.throws(() => composeTemplate("a.html", { "a.html": "@@data@@@@data@@" }), /has 2 @@data@@ markers/);
  assert.throws(() => composeTemplate("a.html", { "a.html": "@@data@@ @@inclde(x)@@" }), /leftover @@/);
});

test("assertSha256Pin passes on a match and names only the hashes on a mismatch", () => {
  const pinned = sha256("page");
  assertSha256Pin("page", pinned, "demo");
  assert.throws(() => assertSha256Pin("secret page text", pinned, "demo"), (err) => {
    assert.match(err.message, new RegExp(`^demo: sha256 [0-9a-f]{64} does not match the pinned ${pinned}$`));
    return !err.message.includes("secret");
  });
});
